"""Check that the requests made by the test suite to /api/ conform to the
OpenAPI schema generated by drf-spectacular.

The schema is given to the WAF, which rejects non-conforming requests: a
request accepted by a view but not described by the schema would be blocked in
production. The middleware below validates, before the view runs, the method,
path, query parameters and body of every /api/ request made through the Django
test client, and makes the test fail otherwise.

Tests deliberately sending invalid requests (to check the view's own error
handling) opt out with ``@pytest.mark.openapi_invalid_request``.
"""

from __future__ import annotations

import copy
import functools
from typing import Any
from urllib.parse import urljoin

from django.http import HttpRequest
from django.http.request import RawPostDataException
from drf_spectacular.generators import SchemaGenerator
from jsonschema_path import SchemaPath
from openapi_core.contrib.django import DjangoOpenAPIRequest
from openapi_core.templating.paths.finders import APICallPathFinder
from openapi_core.validation.request.validators import (
    V30RequestBodyValidator,
    V30RequestParametersValidator,
)

API_PATH_PREFIX = "/api/"
# Swagger UI page, not part of the API itself.
EXCLUDED_PATHS = ("/api/docs",)
# CORS preflight requests are not described by OpenAPI: the WAF must let them
# through to reach the application's CORS handling.
EXCLUDED_METHODS = ("OPTIONS",)


class _ValidationState:  # pylint: disable=too-few-public-methods
    enabled = False


class OpenAPIRequestValidationError(AssertionError):
    pass


def set_validation_enabled(enabled: bool) -> None:
    _ValidationState.enabled = enabled


@functools.cache
def get_schema() -> dict[str, Any]:
    return SchemaGenerator().get_schema(request=None, public=True)


@functools.cache
def _get_spec() -> SchemaPath:
    """Schema used for validation, stricter than the published one: request
    bodies may not contain undeclared fields. DRF ignores unknown fields, so the
    published schema allows them; checking here that the tests never send any
    keeps the declared fields complete."""
    schema = copy.deepcopy(get_schema())
    for component in schema["components"]["schemas"].values():
        if component.get("type") == "object" and "properties" in component:
            component.setdefault("additionalProperties", False)
    return SchemaPath.from_dict(schema)


class _SchemaRequest(DjangoOpenAPIRequest):
    """Match the operation from the URL, like the WAF does, instead of the
    Django route (whose parameter names may differ from the schema, e.g. pk)."""

    path_pattern = None  # type: ignore[assignment]

    def __init__(self, request: HttpRequest):
        super().__init__(request)
        # Path parameters are then extracted from the URL by openapi-core.
        self.parameters.path = {}


def _undeclared_query_parameters(
    openapi_request: _SchemaRequest,
) -> list[str]:
    path, _operation, *_ = APICallPathFinder(_get_spec()).find(
        openapi_request.method,
        urljoin(openapi_request.host_url, openapi_request.path),
    )
    path_item = get_schema()["paths"][path.parts[-1]]
    declared = {
        parameter["name"]
        for parameter in (
            *path_item.get("parameters", []),
            *path_item[openapi_request.method].get("parameters", []),
        )
        if parameter["in"] == "query"
    }
    return sorted(set(openapi_request.parameters.query) - declared)


def validate_request(request: HttpRequest) -> None:
    """Raise OpenAPIRequestValidationError if the request does not conform."""
    try:
        request.body  # pylint: disable=pointless-statement
    except RawPostDataException as error:
        raise OpenAPIRequestValidationError(
            "Request body was read before OpenAPI validation."
        ) from error

    openapi_request = _SchemaRequest(request)
    description = f"{request.method} {request.get_full_path()}"
    for validator_class in (V30RequestParametersValidator, V30RequestBodyValidator):
        try:
            validator_class(_get_spec()).validate(openapi_request)
        except Exception as error:  # pylint: disable=broad-exception-caught
            details = getattr(error, "errors", None) or [
                getattr(error, "__cause__", None) or error
            ]
            raise OpenAPIRequestValidationError(
                f"{description} does not conform to the OpenAPI schema: "
                f"{error!r} {details!r}"
            ) from error

    undeclared = _undeclared_query_parameters(openapi_request)
    if undeclared:
        raise OpenAPIRequestValidationError(
            f"{description} sends query parameters missing from the OpenAPI "
            f"schema: {', '.join(undeclared)}"
        )


class OpenAPIRequestValidationMiddleware:
    """Test-only middleware, installed by the root conftest."""

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request: HttpRequest):
        return self.get_response(request)

    def process_view(
        self, request: HttpRequest, view_func, view_args, view_kwargs
    ):  # pylint: disable=unused-argument
        if (
            _ValidationState.enabled
            and request.method not in EXCLUDED_METHODS
            and request.path.startswith(API_PATH_PREFIX)
            and not request.path.startswith(EXCLUDED_PATHS)
        ):
            validate_request(request)
